"""Generate the short list of Online Resources embedded in the manuscript.

The manuscript must not carry the full appendix (that is submitted as its own
file), but Quarto can only resolve `@or-...` against float divs that exist in
the same document -- drop them and every reference renders as "?@or-icons".

So review.qmd includes this generated list instead: the same divs, in the same
order, holding only their captions. Numbering therefore matches the standalone
appendix exactly, and the manuscript ends with a plain list of the supplementary
items, which is what journals ask for anyway.

Run from 90_review/ after editing captions in 92_appendix/or-NN-*.qmd.
_verify_icons.py fails if the two drift apart.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent / "92_appendix"
FULL = ROOT / "_online-resources.qmd"
LIST = ROOT / "_online-resources-list.qmd"


def source_text() -> str:
    """Follow include order in `_online-resources.qmd` (first mention in the article)."""
    includes = re.findall(
        r"\{\{<\s*include\s+(or-\d\d-[\w.-]+\.qmd)\s*>\}\}",
        FULL.read_text(encoding="utf8"),
    )
    if includes:
        parts = []
        for name in includes:
            path = ROOT / name
            if not path.exists():
                sys.exit(f"missing include {name}")
            parts.append(path.read_text(encoding="utf8"))
        return "\n\n".join(parts)
    parts = sorted(ROOT.glob("or-[0-9][0-9]-*.qmd"))
    if parts:
        return "\n\n".join(p.read_text(encoding="utf8") for p in parts)
    return FULL.read_text(encoding="utf8")

HEADER = """<!-- GENERATED by _build_or_list.py -- do not edit by hand.

Captions only, taken from _online-resources.qmd. review.qmd includes this file
so that the `@or-...` references resolve and get the same numbers as the
standalone appendix, without carrying the full tables in the manuscript.
-->
"""


def blocks(text: str):
    """Yield (id, caption) for every `::: {#or-...}` div, in document order."""
    for match in re.finditer(r"::: \{#(or-[\w-]+)\}\n(.*?)\n:::", text, re.S):
        or_id, body = match.group(1), match.group(2)
        # the caption is the last paragraph of the div
        paragraphs = [p.strip() for p in body.split("\n\n") if p.strip()]
        if not paragraphs:
            sys.exit(f"{or_id}: empty div, no caption to lift")
        caption = " ".join(paragraphs[-1].split())
        if caption.startswith(("|", "```", "![", "<!--")):
            sys.exit(f"{or_id}: last paragraph is not a caption: {caption[:60]!r}")
        yield or_id, caption


found = list(blocks(source_text()))
if not found:
    sys.exit("no or-* divs found")

# A float whose only paragraph is the caption is treated as content instead, and
# prints as "<text> / Online Resource N". The empty comment gives Quarto a body
# to attach the caption to, so the entries read "Online Resource N: <text>"; the
# comment itself is dropped by both writers.
out = [HEADER]
for or_id, caption in found:
    out.append(f"::: {{#{or_id}}}\n<!-- -->\n\n{caption}\n:::\n")
LIST.write_text("\n".join(out), encoding="utf8")

print(f"{LIST.name}: {len(found)} resources")
for i, (or_id, caption) in enumerate(found, 1):
    print(f"  {i:>2}. {or_id:18} {caption[:64]}")
